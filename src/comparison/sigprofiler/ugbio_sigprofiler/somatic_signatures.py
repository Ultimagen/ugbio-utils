"""COSMIC mutational-signature analysis of a somatic VCF with the SigProfiler suite.

Runs in its own virtual environment (see the README next to this package), because the
SigProfiler packages need numpy>=2 while the ugbio workspace pins numpy<2. The caller,
``ugbio_comparison.sigprofiler_runner``, starts it as a subprocess.

The reference genome is installed from a local SigProfiler archive (``GRCh38.tar.gz``)
into a writable directory, so nothing is downloaded at runtime.

Outputs in ``--output_dir``:

* ``<context>_profile.tsv``: the sample mutation matrix (SBS96, ID83, DBS78)
* ``<context>_activity.tsv``: the activity of every COSMIC signature assigned to the sample
* ``final_results/``: PNG plots of the sample profile and of every assigned signature
* ``summary.json``: sample name and the contexts that had mutations
"""

from __future__ import annotations

import argparse
import json
import logging
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

import pandas as pd
from SigProfilerAssignment import Analyzer
from SigProfilerMatrixGenerator.scripts.reference_genome_manager import ReferenceGenomeManager
from SigProfilerMatrixGenerator.scripts.SigProfilerMatrixGeneratorFunc import SigProfilerMatrixGeneratorFunc
from sigProfilerPlotting import plotDBS, plotID, plotSBS

logger = logging.getLogger("somatic_signatures")

PROJECT_NAME = "sample"
SIGNATURES_PROJECT_NAME = "somatic_sig"
FINAL_RESULTS_DIR = "final_results"
SUMMARY_FILE = "summary.json"


@dataclass(frozen=True)
class SignatureContext:
    """A mutation context analyzed by SigProfiler.

    Attributes
    ----------
    name : str
        Context name used in the output files (e.g. ``SBS96``)
    matrix : str
        Path of the matrix generated by SigProfilerMatrixGenerator, relative to its ``output`` directory
    fit_context : str
        ``context_type`` passed to SigProfilerAssignment
    plot_type : str
        ``plot_type`` passed to sigProfilerPlotting
    """

    name: str
    matrix: str
    fit_context: str
    plot_type: str

    def plot(self, matrix_path: Path, output_dir: Path, project: str, *, percentage: bool) -> None:
        plot_functions = {"SBS96": plotSBS, "ID83": plotID, "DBS78": plotDBS}
        plot_functions[self.name](
            str(matrix_path),
            f"{output_dir}/",
            project,
            self.plot_type,
            percentage=percentage,
            savefig_format="png",
        )

    def png_name(self, column: str) -> str:
        """Name of the PNG that sigProfilerPlotting writes for a matrix column"""
        return f"{self.name[:-2]}_{self.plot_type}_plots_{column}.png"


CONTEXTS = (
    SignatureContext("SBS96", f"SBS/{PROJECT_NAME}.SBS96.all", "96", "96"),
    SignatureContext("ID83", f"ID/{PROJECT_NAME}.ID83.all", "ID", "83"),
    SignatureContext("DBS78", f"DBS/{PROJECT_NAME}.DBS78.all", "DINUC", "78"),
)


def sample_name_from_vcf(vcf: Path) -> str:
    """Sample name SigProfiler gives a VCF: its file name up to the first dot"""
    return vcf.name.split(".")[0]


def prepare_input_vcf(input_vcf: Path, output_dir: Path) -> Path:
    """Copy the variant records of a VCF into an otherwise empty directory.

    SigProfilerMatrixGenerator reads every VCF in a directory. Records without an alternative
    allele (``ALT`` is ``.``, e.g. reference calls after ``bcftools view --trim-alt-alleles``)
    are dropped, because SigProfiler counts them as errors and stops when more than 30% of the
    records are errors.

    Parameters
    ----------
    input_vcf : Path
        VCF, bgzipped VCF or BCF
    output_dir : Path
        Directory to create; must not exist

    Returns
    -------
    Path
        The uncompressed VCF in ``output_dir``
    """
    output_dir.mkdir(parents=True)
    output_vcf = output_dir / f"{sample_name_from_vcf(input_vcf)}.vcf"
    cmd = ["bcftools", "view", "--no-version", "-e", 'ALT="."', "-Ov", "-o", str(output_vcf), str(input_vcf)]
    logger.info(" ".join(cmd))
    subprocess.run(cmd, check=True)
    return output_vcf


def install_genome(genome: str, genome_archive: Path, reference_dir: Path) -> None:
    """Install a SigProfiler reference genome from a local archive, unless it is already installed.

    Parameters
    ----------
    genome : str
        Genome name (e.g. ``GRCh38``)
    genome_archive : Path
        The SigProfiler archive of the genome (``<genome>.tar.gz``, any file name)
    reference_dir : Path
        Writable directory that holds the installed genome
    """
    manager = ReferenceGenomeManager(str(reference_dir))
    if manager.is_genome_installed(genome):
        logger.info(f"{genome} is already installed in {reference_dir}")
        return
    # SigProfiler expects the archive to be called <genome>.tar.gz
    with tempfile.TemporaryDirectory(dir=reference_dir) as archive_dir:
        Path(archive_dir, f"{genome}.tar.gz").symlink_to(genome_archive.resolve())
        manager.install_local_genome(genome, archive_dir)


def generate_matrices(vcf_dir: Path, genome: str, reference_dir: Path) -> Path:
    """Count the mutations of the VCF in ``vcf_dir`` per context; return the matrices directory"""
    SigProfilerMatrixGeneratorFunc(
        PROJECT_NAME,
        genome,
        str(vcf_dir),
        plot=False,
        exome=False,
        bed_file=None,
        chrom_based=False,
        tsb_stat=False,
        seqInfo=False,
        cushion=100,
        volume=str(reference_dir),
    )
    return vcf_dir / "output"


def fit_signatures(
    context: SignatureContext, matrix_path: Path, work_dir: Path, genome: str, cosmic_version: float
) -> tuple[pd.Series, Path]:
    """Assign COSMIC signatures to the sample.

    Returns
    -------
    tuple[pd.Series, Path]
        Activity of each assigned signature (non-zero only), and the matrix of all COSMIC signatures
    """
    Analyzer.cosmic_fit(
        samples=str(matrix_path),
        output=str(work_dir),
        input_type="matrix",
        context_type=context.fit_context,
        genome_build=genome,
        cosmic_version=cosmic_version,
        collapse_to_SBS96=False,
        make_plots=False,
        verbose=False,
    )
    solution = work_dir / "Assignment_Solution"
    activities = pd.read_csv(solution / "Activities" / "Assignment_Solution_Activities.txt", sep="\t", index_col=0)
    sample_activities = activities.iloc[0]
    sample_activities = sample_activities[sample_activities > 0].rename("activity")
    sample_activities.index.name = "signature"
    return sample_activities, solution / "Signatures" / "Assignment_Solution_Signatures.txt"


def analyze_context(
    context: SignatureContext,
    matrices_dir: Path,
    output_dir: Path,
    genome: str,
    cosmic_version: float,
    sample_name: str,
) -> bool:
    """Fit and plot the signatures of one context; return False if the sample has no mutations in it"""
    matrix_path = matrices_dir / context.matrix
    if not matrix_path.is_file() or pd.read_csv(matrix_path, sep="\t", index_col=0).to_numpy().sum() == 0:
        logger.info(f"No {context.name} mutations, skipping")
        return False
    shutil.copy(matrix_path, output_dir / f"{context.name}_profile.tsv")

    work_dir = output_dir / "work" / context.name
    activities, signatures_path = fit_signatures(context, matrix_path, work_dir, genome, cosmic_version)
    activities.to_csv(output_dir / f"{context.name}_activity.tsv", sep="\t")
    logger.info(f"{context.name} signatures: {activities.to_dict()}")

    # Plot only the assigned signatures, not the whole COSMIC catalog
    assigned_signatures_path = work_dir / f"assigned_{context.name}_signatures.tsv"
    signatures = pd.read_csv(signatures_path, sep="\t", index_col=0)
    signatures[activities.index].to_csv(assigned_signatures_path, sep="\t")

    final_results = output_dir / FINAL_RESULTS_DIR
    context.plot(matrix_path, work_dir, PROJECT_NAME, percentage=False)
    shutil.copy(work_dir / context.png_name(sample_name), final_results)
    context.plot(assigned_signatures_path, work_dir, SIGNATURES_PROJECT_NAME, percentage=True)
    for signature in activities.index:
        shutil.copy(work_dir / context.png_name(signature), final_results)
    return True


def run_somatic_signatures(
    output_dir: Path,
    genome: str,
    cosmic_version: float,
    input_vcf: Path | None = None,
    genome_archive: Path | None = None,
    reference_dir: Path | None = None,
    matrices_dir: Path | None = None,
) -> dict:
    """Run the signature analysis from a VCF, or from SigProfilerMatrixGenerator matrices.

    Parameters
    ----------
    output_dir : Path
        Output directory
    genome : str
        Genome name (``GRCh38`` or ``GRCh37``)
    cosmic_version : float
        COSMIC signatures version
    input_vcf : Path, optional
        Somatic VCF; requires ``genome_archive``
    genome_archive : Path, optional
        SigProfiler archive of the genome
    reference_dir : Path, optional
        Where to install the genome, by default ``<output_dir>/sigprofiler_reference``
    matrices_dir : Path, optional
        Existing SigProfilerMatrixGenerator ``output`` directory, used instead of ``input_vcf``

    Returns
    -------
    dict
        The summary also written to ``summary.json``
    """
    (output_dir / FINAL_RESULTS_DIR).mkdir(parents=True, exist_ok=True)
    if matrices_dir is None:
        if input_vcf is None or genome_archive is None:
            raise ValueError("Either input_vcf and genome_archive, or matrices_dir, are required")
        reference_dir = reference_dir or output_dir / "sigprofiler_reference"
        reference_dir.mkdir(parents=True, exist_ok=True)
        install_genome(genome, genome_archive, reference_dir)
        vcf = prepare_input_vcf(input_vcf, output_dir / "input_vcf")
        matrices_dir = generate_matrices(vcf.parent, genome, reference_dir)
    sample_name = pd.read_csv(matrices_dir / CONTEXTS[0].matrix, sep="\t", index_col=0, nrows=1).columns[0]

    contexts = [
        context.name
        for context in CONTEXTS
        if analyze_context(context, matrices_dir, output_dir, genome, cosmic_version, sample_name)
    ]
    summary = {"sample_name": sample_name, "contexts": contexts}
    with open(output_dir / SUMMARY_FILE, "w") as summary_file:
        json.dump(summary, summary_file, indent=2)
    return summary


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(prog="somatic_signatures", description=__doc__.splitlines()[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--input_vcf", type=Path, help="Somatic VCF (plain, bgzipped or BCF)")
    source.add_argument("--matrices_dir", type=Path, help="Existing SigProfilerMatrixGenerator output directory")
    parser.add_argument("--genome_archive", type=Path, help="SigProfiler genome archive (e.g. GRCh38.tar.gz)")
    parser.add_argument("--reference_dir", type=Path, help="Writable directory to install the genome into")
    parser.add_argument("--genome", default="GRCh38", choices=["GRCh38", "GRCh37"], help="Reference genome")
    parser.add_argument("--cosmic_version", type=float, default=3.3, help="COSMIC signatures version")
    parser.add_argument("--output_dir", type=Path, required=True, help="Output directory")
    args = parser.parse_args(argv)
    if args.input_vcf is not None and args.genome_archive is None:
        parser.error("--genome_archive is required with --input_vcf")
    return args


def main(argv: list[str] | None = None) -> None:
    logging.basicConfig(format="%(asctime)s %(levelname)s %(message)s", level=logging.INFO)
    args = parse_args(argv)
    run_somatic_signatures(
        output_dir=args.output_dir,
        genome=args.genome,
        cosmic_version=args.cosmic_version,
        input_vcf=args.input_vcf,
        genome_archive=args.genome_archive,
        reference_dir=args.reference_dir,
        matrices_dir=args.matrices_dir,
    )


if __name__ == "__main__":
    main()
